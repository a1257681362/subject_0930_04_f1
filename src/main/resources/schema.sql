-- H2 本地文件数据库初始化脚本。F1 在此基础上补充业务表。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ==================== 城市地下管网巡检台账 ====================

-- 管段档案：材质、口径、埋深、所属道路；segment_no 全局唯一
CREATE TABLE IF NOT EXISTS t_pipe_segment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_no VARCHAR(64) NOT NULL,
    material VARCHAR(32) NOT NULL,
    diameter_mm INT NOT NULL,
    bury_depth_m DECIMAL(5,2) NOT NULL,
    road_name VARCHAR(128) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'FILED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pipe_segment_no UNIQUE (segment_no)
);

-- 井室档案：坐标、盖板、风险等级；well_no 全局唯一
-- confirm_status: UNCONFIRMED / CONFIRMED，已确认事实不可篡改
CREATE TABLE IF NOT EXISTS t_pipe_well (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    well_no VARCHAR(64) NOT NULL,
    segment_id BIGINT,
    coord_lng DECIMAL(10,6) NOT NULL,
    coord_lat DECIMAL(10,6) NOT NULL,
    cover_type VARCHAR(64) NOT NULL,
    risk_level VARCHAR(16) NOT NULL DEFAULT 'LOW',
    confirm_status VARCHAR(16) NOT NULL DEFAULT 'UNCONFIRMED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pipe_well_no UNIQUE (well_no)
);

-- 井室位置历史：只增不删，任何模式下不提供删除与更新
CREATE TABLE IF NOT EXISTS t_pipe_well_location_hist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    well_id BIGINT NOT NULL,
    coord_lng DECIMAL(10,6) NOT NULL,
    coord_lat DECIMAL(10,6) NOT NULL,
    change_reason VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);

-- 巡检工单：关联巡检人员与路线
-- 状态机: DISPATCHED(已派检) -> FIELD_RECORDED(现场记录已提交) -> CLOSED(复核闭环)
-- 复核退回时回到 DISPATCHED
CREATE TABLE IF NOT EXISTS t_inspect_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL,
    inspector_name VARCHAR(64) NOT NULL,
    route_desc VARCHAR(512),
    status VARCHAR(24) NOT NULL DEFAULT 'DISPATCHED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_inspect_order_no UNIQUE (order_no)
);

-- 巡检路线明细：每站关联一个井室或一段管段
CREATE TABLE IF NOT EXISTS t_inspect_order_route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    well_id BIGINT,
    segment_id BIGINT,
    seq_no INT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);

-- 现场记录：巡检中发现的问题
CREATE TABLE IF NOT EXISTS t_inspect_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    well_id BIGINT,
    segment_id BIGINT,
    finding_desc VARCHAR(1024),
    has_hazard BOOLEAN NOT NULL DEFAULT FALSE,
    recorded_by VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);

-- 隐患登记：来源于标记了隐患的现场记录
-- 状态机: REGISTERED -> REVIEW_PASS / REVIEW_REJECT
-- （抢修结算后续迭代扩展 REPAIRING / SETTLED）
CREATE TABLE IF NOT EXISTS t_hazard (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hazard_no VARCHAR(64) NOT NULL,
    order_id BIGINT NOT NULL,
    record_id BIGINT NOT NULL,
    well_id BIGINT,
    segment_id BIGINT,
    hazard_desc VARCHAR(1024) NOT NULL,
    hazard_level VARCHAR(16) NOT NULL DEFAULT 'GENERAL',
    status VARCHAR(24) NOT NULL DEFAULT 'REGISTERED',
    review_comment VARCHAR(512),
    reviewed_by VARCHAR(64),
    reviewed_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_hazard_no UNIQUE (hazard_no)
);

-- 管网权限模式（单行表）：NORMAL / TIGHTENED
-- TIGHTENED 时：管段档案停止推进；井室档案仅保留已确认事实，禁止变更
CREATE TABLE IF NOT EXISTS t_network_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    reason VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);

MERGE INTO t_network_permission (id, mode, reason)
KEY (id)
VALUES (1, 'NORMAL', '初始：正常模式');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('pipe-1', '城市地下管网巡检台账：管段/井室/位置历史/工单/隐患/权限模式');
