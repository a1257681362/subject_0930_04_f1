-- 城市地下管网巡检台账建表脚本（H2 本地文件数据库，启动时自动执行）

-- ============ Schema 版本 ============
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ============ 巡检人员 ============
CREATE TABLE IF NOT EXISTS t_inspector (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_no VARCHAR(32) NOT NULL,
    name VARCHAR(64) NOT NULL,
    phone VARCHAR(32),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_inspector_emp_no UNIQUE (employee_no)
);

-- ============ 管段档案：材质、口径、埋深、所属道路 ============
CREATE TABLE IF NOT EXISTS t_pipe_segment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segment_no VARCHAR(40) NOT NULL,
    material VARCHAR(64),
    diameter_mm INT,
    burial_depth_m DECIMAL(6,2),
    road_name VARCHAR(128),
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    confirmed_at TIMESTAMP,
    remarks VARCHAR(500),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pipe_segment_no UNIQUE (segment_no)
);

-- ============ 井室档案：坐标、盖板、风险等级 ============
CREATE TABLE IF NOT EXISTS t_manhole (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manhole_no VARCHAR(40) NOT NULL,
    lng DECIMAL(12,8),
    lat DECIMAL(12,8),
    cover_type VARCHAR(64),
    risk_level VARCHAR(8),
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    confirmed_at TIMESTAMP,
    remarks VARCHAR(500),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_manhole_no UNIQUE (manhole_no)
);

-- ============ 井室历史位置：只追加，应用层不提供修改/删除路径 ============
CREATE TABLE IF NOT EXISTS t_manhole_location_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manhole_id BIGINT NOT NULL,
    lng DECIMAL(12,8) NOT NULL,
    lat DECIMAL(12,8) NOT NULL,
    change_remark VARCHAR(255),
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_manhole_loc_hist_manhole ON t_manhole_location_history (manhole_id);

-- ============ 巡检路线 ============
CREATE TABLE IF NOT EXISTS t_inspection_route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_name VARCHAR(80) NOT NULL,
    remarks VARCHAR(500),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_route_name UNIQUE (route_name)
);

-- 路线明细：挂接管段或井室
CREATE TABLE IF NOT EXISTS t_route_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    target_type VARCHAR(16) NOT NULL,
    target_id BIGINT NOT NULL,
    seq_no INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_route_item_route ON t_route_item (route_id);

-- ============ 巡检工单：关联人员、路线 ============
CREATE TABLE IF NOT EXISTS t_inspection_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(40) NOT NULL,
    route_id BIGINT NOT NULL,
    assignee_id BIGINT NOT NULL,
    planned_time TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'ASSIGNED',
    started_at TIMESTAMP,
    finished_at TIMESTAMP,
    remarks VARCHAR(500),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_inspection_order_no UNIQUE (order_no)
);
CREATE INDEX IF NOT EXISTS idx_inspection_order_assignee ON t_inspection_order (assignee_id);

-- ============ 现场巡检记录 ============
CREATE TABLE IF NOT EXISTS t_field_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    target_type VARCHAR(16) NOT NULL,
    target_id BIGINT NOT NULL,
    inspector_id BIGINT NOT NULL,
    record_time TIMESTAMP NOT NULL,
    condition_status VARCHAR(64),
    content VARCHAR(2000),
    has_issue BOOLEAN NOT NULL DEFAULT FALSE,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_field_record_order ON t_field_record (order_id);

-- ============ 隐患登记与复核闭环 ============
CREATE TABLE IF NOT EXISTS t_hidden_danger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hazard_no VARCHAR(40) NOT NULL,
    source_type VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    order_id BIGINT,
    field_record_id BIGINT,
    target_type VARCHAR(16) NOT NULL,
    target_id BIGINT NOT NULL,
    description VARCHAR(2000) NOT NULL,
    severity VARCHAR(8) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(20) NOT NULL DEFAULT 'REGISTERED',
    registrar_id BIGINT,
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    rectification_note VARCHAR(2000),
    rectified_by BIGINT,
    rectified_at TIMESTAMP,
    review_conclusion VARCHAR(2000),
    review_by BIGINT,
    review_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_hazard_no UNIQUE (hazard_no)
);
CREATE INDEX IF NOT EXISTS idx_hazard_target ON t_hidden_danger (target_type, target_id);
CREATE INDEX IF NOT EXISTS idx_hazard_status ON t_hidden_danger (status);

-- ============ 系统配置（权限收紧开关等） ============
CREATE TABLE IF NOT EXISTS t_sys_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key VARCHAR(128) NOT NULL,
    config_value VARCHAR(512),
    description VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_sys_config_key UNIQUE (config_key)
);

MERGE INTO t_sys_config (config_key, config_value, description)
KEY (config_key)
VALUES ('network.permission.restricted', 'false',
        '城市地下管网权限收紧开关：true 时管段档案停止推进，井室档案仅保留已确认事实');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('pipe-1', '城市地下管网巡检台账：管段/井室建档、派检、现场记录、隐患登记与复核闭环');
